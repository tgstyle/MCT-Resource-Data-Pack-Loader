    private static void onCommonSetup(FMLCommonSetupEvent event) {
        PackFinder.ensureScanned();
        PackManager.get().warnAboutDisabledFeatures();
        event.enqueueWork(ContentRegistry::resolveStacks);
        event.enqueueWork(ZoneRules::load);
        event.enqueueWork(ContentRegistry::resolveFluidReactions);
        event.enqueueWork(ContentPotions::applyBrewing);
        event.enqueueWork(ScriptRegistries::report);
        ContentFtbTeams.install();
        ContentFtbChunks.install();
        ContentAdAstra.install();
        Set<String> missing = PackRequirements.required();
        if (missing.isEmpty()) {
            RegistryRemaps.reload();
            event.enqueueWork(() -> {
                ContentSpawners.apply();
                ShieldIndexes.resolve();
                ContentPortals.bind();
                ContentHardness.setup();
                ContentAnvils.load();
                ContentAffixes.load();
                ContentEnchanting.load();
                ContentSleep.load();
                FireworkDispensing.register();
                ContentFluids.registerDispensing();
                if (ContentOrders.load()) {
                    MinecraftForge.EVENT_BUS.addListener(ContentOrders::onLevelTick);
                    MinecraftForge.EVENT_BUS.addListener(ContentOrders::onPlace);
                    MinecraftForge.EVENT_BUS.addListener(ContentOrders::onBreak);
                    MinecraftForge.EVENT_BUS.addListener(ContentOrders::onChunkLoad);
                    MinecraftForge.EVENT_BUS.addListener(ContentOrders::onInteract);
                }
                if (ContentRanks.load()) {
                    MinecraftForge.EVENT_BUS.addListener(EventPriority.LOW, ContentRanks::onJoin);
                    MinecraftForge.EVENT_BUS.addListener(ContentRanks::onTick);
                    MinecraftForge.EVENT_BUS.addListener(ContentRanks::onDeath);
                    MinecraftForge.EVENT_BUS.addListener(EventPriority.HIGH, ContentRanks::onDrops);
                    if (ContentRanks.stealing()) { MinecraftForge.EVENT_BUS.addListener(EventPriority.LOWEST, RankSteal::onOpen); }
                }
                ContentOverrides.reload();
                ContentWeights.load();
            });
            return;
        }
        String message = "Packs require mods that are not installed: " + String.join(", ", missing) + ". Install them or remove the packs that need them";
        ContentLog.LOGGER.fatal(message);
        throw new IllegalStateException(message);
    }

