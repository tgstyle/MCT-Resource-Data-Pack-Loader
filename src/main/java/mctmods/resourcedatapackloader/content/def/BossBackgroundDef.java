package mctmods.resourcedatapackloader.content.def;

public final class BossBackgroundDef {
    public final String texture;
    public final int width;
    public final int height;
    public final int x;
    public final int y;

    public BossBackgroundDef(String texture, int width, int height, int x, int y) {
        this.texture = texture;
        this.width = width;
        this.height = height;
        this.x = x;
        this.y = y;
    }
}
